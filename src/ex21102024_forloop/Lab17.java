package ex21102024_forloop;

public class Lab17 {
    public static void main(String[] args) {
        for (int i = 1; i <= 10 ; i++) {
            if(i%2==1)
            {
                System.out.println("Odd ->"+i);
            }
            else if(i%2==0)
            {
                System.out.println("Even ->"+i);
            }
            }
    }
}
